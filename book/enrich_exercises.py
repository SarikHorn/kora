# Function to build rich exercise HTML
def format_exercise_html(ex_obj, index):
    steps_list = ''.join([f'<li><span class="step-badge">{i+1}</span> <span>{step}</span></li>' for i, step in enumerate(ex_obj['instructions'])])
    
    sample_box = ''
    if ex_obj.get('sample_text'):
        escaped_sample = ex_obj['sample_text'].replace('\n', '<br>')
        sample_box = f'''
        <div class="ex-sample-box">
          <div class="ex-box-header">📋 ទិន្នន័យគំរូសម្រាប់អនុវត្ត (Sample Data)</div>
          <div class="ex-sample-content">{escaped_sample}</div>
        </div>
        '''

    tips_box = ''
    if ex_obj.get('tips'):
        tips_box = f'''
        <div class="ex-tips-box">
          <div class="ex-tips-header">💡 គន្លឹះសំខាន់ និងផ្លូវកាត់ (Pro Tips)</div>
          <div class="ex-tips-content">{ex_obj['tips']}</div>
        </div>
        '''

    copy_payload = f"{ex_obj['title']}\\n\\nគោលបំណង៖ {ex_obj['objective']}\\n\\nជំហានអនុវត្ត៖\\n"
    for i, s in enumerate(ex_obj['instructions']):
        clean_s = re.sub(r'<[^>]+>', '', s)
        copy_payload += f"{i+1}. {clean_s}\\n"
    if ex_obj.get('sample_text'):
        copy_payload += f"\\nទិន្នន័យគំរូ៖\\n{ex_obj['sample_text']}\\n"

    html_card = f'''
    <div class="exercise-card" id="ex-{index}">
      <div class="ex-header-row">
        <div class="ex-title-wrap">
          <span class="ex-badge-pill">📝 កិច្ចការផ្ទះ</span>
          <h3 class="ex-title">{ex_obj['title']}</h3>
        </div>
        <button class="card-copy-btn" onclick="window.appCopyText('{copy_payload}')">
          <span>📋</span> ចម្លងកិច្ចការ
        </button>
      </div>

      <div class="ex-objective">
        🎯 <strong>គោលបំណង៖</strong> {ex_obj['objective']}
      </div>

      <div class="ex-steps-wrap">
        <div class="ex-steps-header">🛠️ សេចក្ដីណែនាំ និងជំហានអនុវត្ត (Step-by-Step Instructions)៖</div>
        <ul class="ex-steps-list">
          {steps_list}
        </ul>
      </div>

      {sample_box}
      {tips_box}
    </div>
    '''
    return html_card

