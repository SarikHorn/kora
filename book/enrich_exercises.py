added_exercises_count = 0

for mod in data['modules']:
    mod_id = mod['id']
    if mod_id not in ['word', 'powerpoint', 'excel']:
        continue

    for ch in mod['chapters']:
        ch_id = ch['id']
        if ch_id in exercises_data:
            ex_list = exercises_data[ch_id]

            # Find if there is an existing exercise section in this chapter
            target_sec = None
            for sec in ch['sections']:
                if 'លំហាត់' in sec['title'] or 'អនុវត្ត' in sec['title'] or 'កិច្ចការ' in sec['title']:
                    target_sec = sec
                    break

            # If no exercise section exists, create a new one
            if not target_sec:
                sec_num = len(ch['sections']) + 1
                target_sec = {
                    'id': f'{ch_id}-sec{sec_num}',
                    'secNum': sec_num,
                    'title': f'ផ្នែកទី {sec_num}៖ លំហាត់អនុវត្តន៍ និងកិច្ចការផ្ទះ (Homework Exercises)',
                    'html': '',
                    'images': [],
                    'tools': [],
                    'isExerciseSection': True
                }
                ch['sections'].append(target_sec)
            else:
                target_sec['isExerciseSection'] = True

            # Build HTML for all exercises in this chapter
            ex_cards_html = []
            for idx, ex in enumerate(ex_list):
                tool_id = f"{target_sec['id']}-ex{idx+1}"
                ex_html = format_exercise_html(ex, idx+1)
                ex_cards_html.append(ex_html)

                # Also add as an individual tool node so it appears in the tree!
                # Check if tool already exists
                existing_tool = next((t for t in target_sec.get('tools', []) if t['title'] == ex['title']), None)
                if not existing_tool:
                    tool_node = {
                        'id': tool_id,
                        'title': ex['title'],
                        'definition': f"គោលបំណង៖ {ex['objective']}",
                        'procedure': 'អនុវត្តតាមជំហានណែនាំលម្អិតក្នុងកិច្ចការផ្ទះ។',
                        'shortcut': '',
                        'steps': [re.sub(r'<[^>]+>', '', s) for s in ex['instructions'][:4]],
                        'html': ex_html,
                        'images': [],
                        'isExercise': True,
                        'breadcrumbs': [
                            mod['title'],
                            ch['title'],
                            target_sec['title'],
                            ex['title']
                        ]
                    }
                    if 'tools' not in target_sec:
                        target_sec['tools'] = []
                    target_sec['tools'].append(tool_node)
                    added_exercises_count += 1

            # Append the full rich HTML to the section
            intro_html = f'''
            <div class="ex-section-intro">
              <h2 style="font-size: 1.35rem; font-weight: 800; color: var(--text-primary); margin-bottom: 6px;">
                📝 កិច្ចការផ្ទះ និងលំហាត់អនុវត្តន៍សម្រាប់ព័ន្ធកិច្ច ({len(ex_list)} កិច្ចការ)
              </h2>
              <p style="font-size: 0.92rem; color: var(--text-muted); margin-bottom: 20px;">
                កិច្ចការផ្ទះទាំងនេះត្រូវបានរៀបចំឡើងយ៉ាងផ្ចិតផ្ចង់ ដោយផ្អែកលើតម្រូវការជាក់ស្ដែងនៃការបម្រើព្រះក្នុងពួកជំនុំ។ សូមសិស្សានុសិស្សអនុវត្តតាមជំហានខាងក្រោម ដើម្បីពង្រឹងការយល់ដឹងឱ្យកាន់តែស៊ីជម្រៅ។
              </p>
            </div>
            '''
            target_sec['html'] = intro_html + ''.join(ex_cards_html)

